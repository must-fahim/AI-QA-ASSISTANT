"use client";

import { Alert, Button, Dropdown, Input, Select, Space, Table, Tag } from "antd";
import type { TableColumnsType } from "antd";
import { Download, Pencil, Trash2 } from "lucide-react";
import { useMemo, useState } from "react";
import { PRIORITY_WEIGHT } from "@/constants/limits";
import { buildCsvFilename, buildTestCasesCsv } from "@/lib/csv/export-test-cases";
import { downloadCsv } from "@/lib/csv/download";
import { formatDuration } from "@/lib/format";
import type { EditableTestCase, Priority } from "@/types/domain";

const PRIORITY_COLOR: Record<string, string> = {
  Critical: "red",
  High: "volcano",
  Medium: "gold",
  Low: "default",
};

export function ResultsPanel({
  title,
  model,
  persisted,
  saving,
  generationDurationMs,
  requirementSummary,
  assumptions,
  clarificationQuestions,
  cases,
  onOpen,
  onDelete,
  onSaveSuite,
}: {
  title: string;
  model?: string | null;
  persisted: boolean;
  saving?: boolean;
  generationDurationMs?: number | null;
  requirementSummary: string;
  assumptions: string[];
  clarificationQuestions: string[];
  cases: EditableTestCase[];
  onOpen: (testCase: EditableTestCase, mode: "view" | "edit") => void;
  onDelete: (testCase: EditableTestCase) => void;
  onSaveSuite?: () => void;
}) {
  const [query, setQuery] = useState("");
  const [category, setCategory] = useState<string>("all");
  const [priority, setPriority] = useState<string>("all");
  const [selectedKeys, setSelectedKeys] = useState<string[]>([]);

  const categories = useMemo(
    () => [...new Set(cases.map((testCase) => testCase.category))],
    [cases],
  );

  const filtered = useMemo(() => {
    const needle = query.trim().toLowerCase();
    return cases.filter((testCase) => {
      const matchesQuery =
        !needle ||
        testCase.id.toLowerCase().includes(needle) ||
        testCase.title.toLowerCase().includes(needle) ||
        testCase.tags.some((tag) => tag.toLowerCase().includes(needle));
      const matchesCategory = category === "all" || testCase.category === category;
      const matchesPriority = priority === "all" || testCase.priority === priority;
      return matchesQuery && matchesCategory && matchesPriority;
    });
  }, [cases, category, priority, query]);

  const columns: TableColumnsType<EditableTestCase> = [
    { title: "Test Case ID", dataIndex: "id", sorter: (a, b) => a.id.localeCompare(b.id), width: 130 },
    { title: "Title", dataIndex: "title", sorter: (a, b) => a.title.localeCompare(b.title) },
    {
      title: "Category",
      dataIndex: "category",
      sorter: (a, b) => a.category.localeCompare(b.category),
      render: (value: string) => <Tag>{value}</Tag>,
    },
    {
      title: "Priority",
      dataIndex: "priority",
      sorter: (a, b) => (PRIORITY_WEIGHT[a.priority] ?? 0) - (PRIORITY_WEIGHT[b.priority] ?? 0),
      width: 120,
      render: (value: Priority) => <Tag color={PRIORITY_COLOR[value] ?? "default"}>{value}</Tag>,
    },
    {
      title: "Actions",
      width: 150,
      render: (_value, record) => (
        <Space>
          <Button size="small" onClick={() => onOpen(record, "view")}>
            View
          </Button>
          <Button size="small" icon={<Pencil size={14} />} onClick={() => onOpen(record, "edit")} aria-label={`Edit ${record.id}`} />
          <Button
            size="small"
            danger
            icon={<Trash2 size={14} />}
            onClick={() => onDelete(record)}
            aria-label={`Delete ${record.id}`}
          />
        </Space>
      ),
    },
  ];

  function exportCases(scope: "all" | "selected" | "filtered") {
    const selected = new Set(selectedKeys);
    const rows =
      scope === "all"
        ? cases
        : scope === "selected"
          ? cases.filter((testCase) => selected.has(testCase.recordId ?? testCase.id))
          : filtered;
    downloadCsv(buildCsvFilename(title), buildTestCasesCsv(rows));
  }

  const categoryCounts = countValues(cases.map((testCase) => testCase.category));
  const priorityCounts = countValues(cases.map((testCase) => testCase.priority));

  return (
    <section className="flex flex-col gap-4">
      <Alert
        type={persisted ? "success" : "warning"}
        showIcon
        title={persisted ? "Saved in test history" : "Generated by AI and not saved"}
        description={
          persisted
            ? "Edits to individual test cases are written to the database."
            : model
              ? `Generated by ${model}. Save the suite to retrieve it from Test History.`
              : "Save the suite to retrieve it from Test History."
        }
      />
      <div className="rounded-lg border border-[#e5e7eb] bg-white p-4 shadow-sm">
        <div className="flex flex-wrap items-start justify-between gap-3">
          <div>
            <h2 className="text-base font-semibold">Requirement summary</h2>
            <p className="mt-2 max-w-3xl text-sm leading-6 text-[#374151]">{requirementSummary}</p>
          </div>
          <div className="text-sm text-[#6b7280]">
            <p>{cases.length} test cases</p>
            <p>{formatDuration(generationDurationMs)}</p>
          </div>
        </div>
        <div className="mt-4 grid gap-4 md:grid-cols-2">
          <InfoList title="Assumptions" values={assumptions} empty="No assumptions were recorded." />
          <InfoList
            title="Clarification questions"
            values={clarificationQuestions}
            empty="No clarification questions were recorded."
          />
        </div>
        <div className="mt-4 flex flex-col gap-2">
          <Space wrap>
            <span className="text-xs font-medium text-[#6b7280]">Categories</span>
            {categoryCounts.map(([name, count]) => (
              <Tag key={name}>
                {name} · {count}
              </Tag>
            ))}
          </Space>
          <Space wrap>
            <span className="text-xs font-medium text-[#6b7280]">Priority</span>
            {priorityCounts.map(([name, count]) => (
              <Tag key={name} color={PRIORITY_COLOR[name] ?? "default"}>
                {name} · {count}
              </Tag>
            ))}
          </Space>
        </div>
      </div>

      <div className="rounded-lg border border-[#e5e7eb] bg-white p-4 shadow-sm">
        <div className="mb-4 flex flex-col gap-3 lg:flex-row lg:items-center lg:justify-between">
          <div className="grid flex-1 gap-3 md:grid-cols-3">
            <Input.Search
              allowClear
              placeholder="Search title, ID, or tag"
              value={query}
              onChange={(event) => setQuery(event.target.value)}
            />
            <Select
              value={category}
              onChange={setCategory}
              options={[{ value: "all", label: "All categories" }, ...categories.map((item) => ({ value: item, label: item }))]}
            />
            <Select
              value={priority}
              onChange={setPriority}
              options={[
                { value: "all", label: "All priorities" },
                ...["Critical", "High", "Medium", "Low"].map((item) => ({ value: item, label: item })),
              ]}
            />
          </div>
          <Space>
            {!persisted && onSaveSuite ? (
              <Button type="primary" loading={saving} onClick={onSaveSuite}>
                Save test suite
              </Button>
            ) : null}
            <Dropdown
              menu={{
                items: [
                  { key: "all", label: "Export all" },
                  { key: "selected", label: "Export selected", disabled: selectedKeys.length === 0 },
                  { key: "filtered", label: "Export filtered" },
                ],
                onClick: ({ key }) => exportCases(key as "all" | "selected" | "filtered"),
              }}
            >
              <Button icon={<Download size={16} />}>Export CSV</Button>
            </Dropdown>
          </Space>
        </div>
        <Table
          rowKey={(record) => record.recordId ?? record.id}
          dataSource={filtered}
          columns={columns}
          pagination={{ pageSize: 20, hideOnSinglePage: true }}
          rowSelection={{
            selectedRowKeys: selectedKeys,
            onChange: (keys) => setSelectedKeys(keys.map(String)),
          }}
          locale={{ emptyText: "No test cases match the current filters." }}
        />
      </div>
    </section>
  );
}

function InfoList({ title, values, empty }: { title: string; values: string[]; empty: string }) {
  return (
    <div>
      <h3 className="text-sm font-semibold">{title}</h3>
      {values.length ? (
        <ul className="mt-2 list-disc pl-5 text-sm text-[#374151]">
          {values.map((value) => (
            <li key={value}>{value}</li>
          ))}
        </ul>
      ) : (
        <p className="mt-2 text-sm text-[#6b7280]">{empty}</p>
      )}
    </div>
  );
}

function countValues(values: string[]) {
  const counts = new Map<string, number>();
  for (const value of values) counts.set(value, (counts.get(value) ?? 0) + 1);
  return [...counts.entries()];
}
