"use client";

import { Alert, Modal, Tag } from "antd";
import type { RequirementExample } from "@/types/domain";

export function SampleOutputModal({
  example,
  onClose,
}: {
  example: RequirementExample | null;
  onClose: () => void;
}) {
  return (
    <Modal
      open={Boolean(example)}
      title={example ? `Sample output · ${example.title}` : "Sample output"}
      onCancel={onClose}
      footer={null}
      width={760}
    >
      {example ? (
        <div className="flex flex-col gap-4">
          <Alert
            type="info"
            showIcon
            title="This is sample output"
            description="These cases were written as a predefined example. They were not generated by the AI model and are not saved in the database."
          />
          <p className="text-sm text-[#374151]">{example.sample.requirementSummary}</p>
          <section>
            <h3 className="mb-2 text-sm font-semibold">Assumptions</h3>
            <ul className="list-disc pl-5 text-sm text-[#374151]">
              {example.sample.assumptions.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          </section>
          <section>
            <h3 className="mb-2 text-sm font-semibold">Clarification questions</h3>
            <ul className="list-disc pl-5 text-sm text-[#374151]">
              {example.sample.clarificationQuestions.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          </section>
          <div className="flex flex-col gap-3">
            {example.sample.testCases.map((testCase) => (
              <article key={testCase.id} className="rounded-lg border border-[#e5e7eb] p-3">
                <div className="flex flex-wrap items-center gap-2">
                  <span className="font-mono text-xs text-[#6b7280]">{testCase.id}</span>
                  <strong className="text-sm">{testCase.title}</strong>
                  <Tag>{testCase.category}</Tag>
                  <Tag color="purple">{testCase.priority}</Tag>
                </div>
                <p className="mt-2 text-sm text-[#374151]">{testCase.expectedResult}</p>
              </article>
            ))}
          </div>
        </div>
      ) : null}
    </Modal>
  );
}
